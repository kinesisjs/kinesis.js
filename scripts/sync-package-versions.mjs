/**
 * Writes each publishable package's version into `src/version.ts`.
 *
 * The VERSION constant used to be hand-written and drifted from package.json in
 * every package at once -- @kinesisjs/core@0.5.1 shipped `VERSION === '0.1.0'`.
 * Nothing caught it, because the constant is only ever read by consumers.
 *
 * Changesets bumps package.json, so this runs right after it (see the
 * `changeset:version` script) and the release PR carries the synced constants.
 * `pnpm verify` fails if the two ever disagree -- see each package's index test.
 */
import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs';
import { join } from 'node:path';

const PACKAGES_DIR = 'packages';

const header = `// Generated by scripts/sync-package-versions.mjs -- do not edit by hand.
// Kept in step with package.json by the \`changeset:version\` script.
`;

let changed = 0;
for (const name of readdirSync(PACKAGES_DIR)) {
  const pkgPath = join(PACKAGES_DIR, name, 'package.json');
  if (!existsSync(pkgPath)) continue;

  const pkg = JSON.parse(readFileSync(pkgPath, 'utf8'));
  if (pkg.private) continue;

  const target = join(PACKAGES_DIR, name, 'src', 'version.ts');
  const next = `${header}\nexport const VERSION = '${pkg.version}' as const;\n`;
  const current = existsSync(target) ? readFileSync(target, 'utf8') : null;

  if (current !== next) {
    writeFileSync(target, next);
    console.log(`  synced ${pkg.name} -> ${pkg.version}`);
    changed++;
  }
}

console.log(
  changed === 0 ? '  all package versions already in sync' : `  ${changed} file(s) written`,
);
